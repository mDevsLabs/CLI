export function getMaiModelById(id: string): MaiModel | undefined {
  return MAI_MODELS.find(m => m.id === id)
}

export function getMaiModelContextWindow(id: string): number {
  const model = getMaiModelById(id)
  return model ? model.maxContext : 128000
}

export function getMaiModelMaxOutput(id: string): number {
  const model = getMaiModelById(id)
  return model ? model.maxOutput : 8192
}

export function getLocalModelOptions(): ModelOption[] {
  const subType = getSubscriptionType()
  const isPaid =
    subType === 'max' ||
    subType === 'pro' ||
    subType === 'plus' ||
    subType === 'team' ||
    subType === 'enterprise'
  const isFree = !isPaid

  const options = MAI_MODELS.filter(m => {
    const isModelFree = m.id.includes(':free')
    if (isFree && !isModelFree) return false
    return true
  }).map(m => {
    const label = m.name
    const description = `Provider: ${m.provider} | Context: ${m.maxContext.toLocaleString()} | Output: ${m.maxOutput.toLocaleString()}`
    return {
      value: m.id as any,
      label,
      description,
    }
  })

  return [
    {
      value: null as any,
      label: 'Default (recommended)',
      description: 'Use the default model for your plan',
    },
    ...options,
  ]
}
